import { expect, test } from "@playwright/test";
import { candles } from "./scenarios";
import { newOwner, open } from "./support";

test("daily workflows: configure, review, persist and try demos", async ({ browser }) => {
  const { page } = await newOwner(browser, candles);
  await open(page, "/run");
  await page.getByRole("region", { name: "Connect your email" }).getByRole("link", { name: "Set this up" }).click();
  const today = page.getByRole("definition").filter({ hasText: /made-up customer email/ });
  await expect(today).toBeVisible();
  await expect(page.getByText(/Connecting an email account isn’t available yet/)).toBeVisible();
  await expect(page.getByText("Demo setup.", { exact: true })).toHaveCount(0);
  await page.getByRole("checkbox", { name: "Draft customer replies" }).uncheck();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByLabel("Business email to connect later").fill("hello@example.com");
  await page.getByLabel("Follow up if still waiting after").selectOption("3");
  await page.getByRole("button", { name: "Review setup" }).click();
  await expect(page.getByRole("region", { name: "Review your workflow" })).toContainText("Flag customer messages for your attention");
  await page.getByRole("button", { name: "Approve & save demo setup" }).click();
  await expect(page.getByRole("region", { name: "Your saved workflow" })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("region", { name: "Your saved workflow" })).toContainText("hello@example.com");
  await page.getByRole("button", { name: "Try a demo" }).click();
  await expect(page.getByRole("region", { name: "DEMO · Customer email" })).toContainText("No reply was drafted or sent");
  await page.getByRole("button", { name: "Pause demo" }).click();
  await expect(page.getByRole("button", { name: "Try a demo" })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Resume demo" })).toBeVisible();
  await page.reload();
  await expect(page.getByText("Demo paused", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Resume demo" }).click();
  await expect(page.getByRole("button", { name: "Try a demo" })).toBeEnabled();
  await page.getByRole("button", { name: "Edit setup" }).click();
  await page.getByRole("checkbox", { name: "Draft customer replies" }).check();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: "Review setup" }).click();
  await page.getByRole("button", { name: "Approve & save demo setup" }).click();
  await page.getByRole("button", { name: "Try a demo" }).click();
  await expect(page.getByText("Sample reply · Not sent")).toBeVisible();
  await open(page, "/orders");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByLabel("Where do your requests come from?").selectOption("Enter requests myself");
  await page.getByRole("button", { name: "Review setup" }).click();
  await page.getByRole("button", { name: "Approve & save demo setup" }).click();
  await page.getByRole("button", { name: "Try a demo" }).click();
  await expect(page.getByRole("region", { name: "DEMO · Customer request" })).toContainText("stock is unchanged");
  await open(page, "/run");
  await expect(page.getByText("Demo setup saved", { exact: true })).toHaveCount(2);
});
