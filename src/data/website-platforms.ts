// Wix's own link that opens the owner's site dashboard at one page, after they pick the site
function wixDashboard(path: string, button: string): string {
  const url = new URL("https://www.wix.com/my-account/site-selector/");
  url.searchParams.set("buttonText", button);
  url.searchParams.set("title", "Select a Site");
  url.searchParams.set("autoSelectOnSingleSite", "true");
  url.searchParams.set("actionUrl", `https://www.wix.com/dashboard/{{metaSiteId}}/${path}`);
  return url.toString();
}

